/** 完整规程（供 slop_prepare 与 slop_engine_info 输出）。 */
export function rubricFull() {
  return RUBRIC_ORDER.map(id => {
    const item = RUBRIC[id]
    return {
      id,
      layer: item.layer,
      label: item.label,
      question: item.question,
      // 只输出仍在用的具名档（8 分档已停用，见 BAND_KEYS 注释）
      bands: Object.fromEntries(BAND_KEYS.map(key => [key, item.bands[key]])),
      evidence: item.evidence,
      forbidden: item.forbidden,
      naHint: item.naHint,
    }
  })
}

