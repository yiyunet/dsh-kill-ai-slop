/**
 * 判定规程（rubric）—— 插件的核心资产，不是附属文案。
 *
 * ★ 定位（0.7.0）：
 *   插件**不判断**"这份交付好不好"，它规定**该问自己哪 12 个问题、每档长什么样、
 *   什么才算证据、什么理由不算数**。判断由通读全文的模型做，插件负责把判断变成可核的记录。
 *
 * ★ 锚点是「作用式」而非「要件式」：
 *   写成"必须有责任人和期限"会把格式要求重新带回来 —— 政策文件靠条款明确行为，
 *   不需要逐项写项目启动日期；单一合理方案也不必凭空补一个"放弃项"。
 *   所以每一档判的是**作用有没有达成**，不是**要件有没有齐全**。
 *
 * ★ 允许「不适用」：
 *   每格都带 `naHint`，写明什么样的交付**本来就不需要**这一项。
 *   但"不适用"不是免检标签 —— 必须给出理由，且理由要能被原文核。
 */

